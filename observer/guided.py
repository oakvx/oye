"""Finite-state, bounded game demo routine; no LLM or learned actions required.

A *verified* bus prompt may cause a few SPACE presses. OCR is only contextual;
no key may be generated by an unverified OCR phrase or a loading screen.
This is not an anti-cheat workaround and does not attempt to disguise automation.
"""
from __future__ import annotations
from dataclasses import dataclass, field
from collections import deque
import time
from .p1_navigation import RouteHint
from .models import Action
from .behavior import ActivityPlanner, PROFILES


@dataclass
class GuidedExplorer:
    """Short movement/pickaxe policy with bounded obstacle recovery.

    The vision response is a heuristic. No automatic recovery is attempted
    without repeated *reliable* low-motion feedback from translational actions.
    """
    harvest: bool = True
    smooth: bool = False  # Enabled explicitly by LIVE guided modes; preserve v19 legacy tests.
    profile: str = "equilibrato"
    seed: int | None = None
    max_recoveries: int = 3
    motion_threshold: float = .55
    step: int = 0
    low_motion_streak: int = 0
    recovery_count: int = 0
    halted: bool = False
    recovery_plan: deque = field(default_factory=deque)
    last_feedback: str = 'nessuna prova di movimento'
    route_side: str | None = None
    route_confidence: float = 0.0
    cooldown_until: float = 0.0
    cooldown_rounds: int = 0
    last_camera_probe_step: int = -100
    planner: ActivityPlanner = field(init=False, repr=False)

    def __post_init__(self):
        if not 1 <= self.max_recoveries <= 8 or not .1 <= self.motion_threshold <= 5.0:
            raise ValueError('Impostazioni recupero movimento non valide')
        self.planner = ActivityPlanner(profile=self.profile, harvest=self.harvest, seed=self.seed)

    def observe_route(self, hint: RouteHint) -> None:
        if hint.side in ('left', 'right') and hint.confidence >= .23:
            self.route_side = hint.side
            self.route_confidence = hint.confidence
        else:
            self.route_side = None
            self.route_confidence = 0.0

    def observe_motion(self, measured: float | None, reliable: bool,
                       action_name: str = 'forward') -> None:
        # A camera rotation, animation or mouse swing is NOT proof of walking.
        # Only an isolated forward probe can increment the stuck counter.
        if action_name not in ('forward', 'patrol_forward'):
            return
        if not reliable or measured is None:
            self.last_feedback = 'risposta visiva inconcludente'
            return
        if measured < self.motion_threshold:
            self.low_motion_streak += 1
            self.last_feedback = f'spostamento non rilevato ({measured:.2f} px)'
        else:
            self.low_motion_streak = 0
            self.recovery_count = 0
            self.cooldown_rounds = 0
            self.halted = False
            self.last_feedback = f'variazione visiva ({measured:.2f} px); movimento non garantito'
        if self.low_motion_streak < 3:
            return
        self.low_motion_streak = 0
        if self.recovery_count >= self.max_recoveries:
            self.halted = True
            self.recovery_plan.clear()
            self.cooldown_rounds += 1
            self.cooldown_until = time.monotonic() + min(90., 15. * (2 ** (self.cooldown_rounds - 1)))
            self.last_feedback = 'movimento non verificato: pausa controllata, nuovo tentativo dopo intervallo'
            return
        self.recovery_count += 1
        preferred = self.route_side if self.route_confidence >= .23 else ('left' if self.recovery_count % 2 else 'right')
        turn = 'turn_left' if preferred == 'left' else 'turn_right'
        side = 'strafe_left' if preferred == 'left' else 'strafe_right'
        self.recovery_plan.extend((Action('reverse', .28, reason='Recupero: indietreggia'),
                                   Action(turn, .18, reason='Recupero: cambia orientamento'),
                                   Action(side, .35, reason='Recupero: prova lato meno ingombro o alternato'),
                                   Action('forward_jump', .25, reason='Recupero: prova piccolo dislivello'),
                                   Action('forward', .65, reason='Recupero: nuova prova W')))
        self.last_feedback = f'possibile blocco: tentativo recupero {self.recovery_count}/{self.max_recoveries}'

    def next_action(self, learned_hint: Action | None = None, *, now: float | None = None) -> Action:
        if self.halted:
            now = time.monotonic() if now is None else now
            if now < self.cooldown_until:
                self.planner.activity = 'Recupero sospeso · nuova verifica programmata'
                return Action('wait', reason='Spostamento non verificato: osservo e attendo prima di riprovare')
            # New bounded attempt only if caller still has a verified live HUD.
            self.halted = False
            self.recovery_count = 0
            self.recovery_plan.clear()
            self.recovery_plan.extend((Action('reverse', .25, reason='Riprova controllata: arretra'),
                Action('strafe_left' if self.route_side == 'left' else 'strafe_right', .35,
                       reason='Riprova controllata: percorso alternativo'),
                Action('patrol_forward', .55, reason='Riprova controllata: misura movimento')))
            self.last_feedback = 'Nuova prova dopo pausa, HUD da verificare a ogni comando'
        if self.recovery_plan:
            self.planner.activity = 'Recupero ostacolo'
            return self.recovery_plan.popleft()
        # ML suggestions may influence navigation ONLY when prevalidated by
        # Runner, never select combat/menu operations or bypass phase checks.
        safe_hints = {'forward', 'strafe_left', 'strafe_right', 'forward_jump',
                      'forward_look_left', 'forward_look_right', 'turn_left', 'turn_right'}
        if learned_hint is not None and learned_hint.name in safe_hints and self.step % 3 == 2:
            self.step += 1
            return Action(learned_hint.name, min(.65, max(.15, learned_hint.seconds)),
                          reason='Navigazione: suggerimento dalle dimostrazioni confermate')
        if self.smooth:
            # A short isolated turn allows a genuine camera check without
            # confusing forward optical flow with yaw. Never a menu action.
            if self.step >= 8 and self.step - self.last_camera_probe_step >= 20:
                self.last_camera_probe_step = self.step
                self.step += 1
                return Action('turn_left' if self.step % 2 else 'turn_right', .12,
                              reason='Diagnostica telecamera isolata, verifica su prossimo screenshot')
            # Rotate between activities with bounded multi-action plans;
            # no model wait and no unbounded idle in the ground stage.
            if self.harvest and self.step == 0:
                self.step += 1
                return Action('equip_pickaxe', .09, reason='Preparo il piccone per esplorare')
            self.step += 1
            return self.planner.next_action()
        pattern = (
            ('forward', 1.05),
            ('forward_look_left', .20), ('forward', 1.05),
            ('forward_look_right', .20), ('forward', 1.05),
            ('forward_jump', .33), ('forward', .85),
            ('strafe_left', .55), ('forward_look_right', .17),
            ('forward', 1.00), ('strafe_right', .55),
        )
        if self.harvest:
            pattern = (('equip_pickaxe', .09),) + pattern + (
                ('equip_pickaxe', .09), ('forward_harvest', .55),
                ('forward', .85), ('forward_harvest', .55),
                ('forward_look_left', .17), ('forward', .8),
            )
        name, duration = pattern[self.step % len(pattern)]
        self.step += 1
        return Action(name, duration, reason='Routine semplice: cammina, guarda e piccona')


@dataclass
class SimpleMatchRoutine:
    """Pure state machine for lobby→loading→bus→fall→ground.

    Menu clicks remain the responsibility of Brain and require calibration.
    Bus input requires a *template-confirmed* prompt, not a stale OCR line.
    Landing is a conservative estimate and is reported as such.
    """
    harvest: bool = True
    smooth: bool = False
    profile: str = "equilibrato"
    jump_period: float = 1.6
    min_fall: float = 20.0
    bus_attempt_limit: int = 4
    stage: str = 'unknown'
    bus_confirmations: int = 0
    bus_attempts: int = 0
    last_bus_seen: float = -1e9
    last_jump: float = -1e9
    last_air_evidence: float = -1e9
    last_ground_action: float = -1e9
    recovery_limit: int = 3
    recovery_threshold: float = .55
    explorer: GuidedExplorer = field(default_factory=GuidedExplorer)

    def __post_init__(self):
        if self.jump_period < .75 or self.min_fall < 8 or self.bus_attempt_limit not in range(1, 11):
            raise ValueError('Parametri routine non validi')
        self.explorer = GuidedExplorer(harvest=self.harvest, smooth=self.smooth, profile=self.profile, max_recoveries=self.recovery_limit,
                                       motion_threshold=self.recovery_threshold)

    @staticmethod
    def waiting(why: str) -> Action:
        return Action('wait', reason=why)

    def reset(self, stage: str) -> None:
        self.stage = stage
        self.bus_confirmations = 0
        self.bus_attempts = 0
        self.last_bus_seen = -1e9
        self.last_jump = -1e9
        self.last_air_evidence = -1e9
        self.last_ground_action = -1e9
        self.explorer = GuidedExplorer(harvest=self.harvest, smooth=self.smooth, profile=self.profile, max_recoveries=self.recovery_limit,
                                       motion_threshold=self.recovery_threshold)

    def choose(self, *, scene: str, phase: str | None, phase_source: str,
               authorized_ground: bool, spectator: bool, now: float,
               motion_pixels: float | None = None, motion_reliable: bool = False,
               feedback_action: str = "forward", learned_hint: Action | None = None) -> Action:
        if spectator or scene == 'spectator':
            self.reset('spectator')
            return self.waiting('Spettatore: nessun controllo del personaggio')
        if scene in ('lobby', 'results'):
            if self.stage != scene:
                self.reset(scene)
            return self.waiting('Menu: uso soltanto i pulsanti calibrati')
        if scene == 'loading':
            if self.stage != 'loading':
                self.reset('loading')
            return self.waiting('Caricamento: NON premere Spazio alla cieca')

        # Aerial markers override the generic match HUD; the latter can be
        # present in the bus and while skydiving.
        if phase == 'battle_bus':
            if self.stage in ('skydiving', 'ground'):
                return self.waiting('Bus precedente non ripetuto dopo la discesa')
            if self.stage != 'bus':
                self.stage = 'bus'
                self.bus_confirmations = 0
            self.last_bus_seen = now
            if phase_source != 'template calibrato':
                self.bus_confirmations = 0
                return self.waiting('Bus suggerito da OCR: calibra bus_salto per autorizzare Spazio')
            self.bus_confirmations += 1
            if self.bus_confirmations < 2:
                return self.waiting('Conferma prompt SALTA su due frame')
            if self.bus_attempts >= self.bus_attempt_limit:
                return self.waiting('Limite pressioni Spazio raggiunto: controlla bus/discesa')
            if now - self.last_jump < self.jump_period:
                return self.waiting('Attesa fra pressioni Spazio sul bus')
            self.last_jump = now
            self.bus_attempts += 1
            return Action('jump', .09, reason=f'Bus riconosciuto: Spazio {self.bus_attempts}/{self.bus_attempt_limit}')

        if phase == 'skydiving':
            self.stage = 'skydiving'
            self.last_air_evidence = now
            return self.waiting('Discesa in corso: attesa atterraggio')

        if self.stage == 'bus':
            # The bus prompt has vanished after pressing SPACE, a useful but
            # not conclusive signal of successful jump.
            if self.bus_attempts and now - self.last_bus_seen >= .65:
                self.stage = 'skydiving'
                self.last_air_evidence = now
                return self.waiting('Prompt bus scomparso: probabile discesa')
            if now - self.last_bus_seen > 5 and not self.bus_attempts:
                self.stage = 'unknown'
            return self.waiting('Attesa conferma salto dal bus')

        if self.stage == 'skydiving':
            earliest = self.last_jump if self.last_jump > 0 else self.last_air_evidence
            if (not authorized_ground or now - earliest < self.min_fall or
                    now - self.last_air_evidence < 5):
                return self.waiting('Atterraggio non ancora sufficientemente probabile')
            self.stage = 'ground'

        # Loading can show the same HUD as the bus. When this session has
        # explicitly seen loading, never treat the first match HUD as proof of
        # landing if we failed to detect a bus/discesa phase.
        if self.stage == 'loading':
            return self.waiting('Dopo caricamento manca il bus: calibra bus_salto; non presumo l’atterraggio')

        # If starting mid-match (no preceding loading), a stable ground HUD is
        # sufficient to begin a bounded manual-style movement test.
        if not authorized_ground or scene != 'match':
            return self.waiting('Schermata sconosciuta: attendo HUD stabile')
        if self.stage != 'ground':
            self.stage = 'ground'
        if now - self.last_ground_action < .18:
            return self.waiting('Ciclo di movimento limitato')
        if motion_pixels is not None and motion_reliable:
            self.explorer.observe_motion(motion_pixels, True, feedback_action)
        action = self.explorer.next_action(learned_hint)
        if action.name != 'wait':
            self.last_ground_action = now
        return action
